package com.lycanitesmobs.client.renderer.renderapi.client.render.buffer;



public class Vertex {

    private float x;
    
    private float y;
    
    private float z;
    
    private float r;
    
    private float g;
    
    private float b;
    
    private float a;

    public float getA() {
        return a;
    }

    public float getB() {
        return b;
    }

    public float getG() {
        return g;
    }

    public float getR() {
        return r;
    }

    public float getX() {
        return x;
    }

    public float getY() {
        return y;
    }

    public float getZ() {
        return z;
    }

    public Vertex(float x, float y, float z, float r, float g, float b, float a) {
        this.x = x;
        this.y = y;
        this.z = z;
        this.r = r;
        this.g = g;
        this.b = b;
        this.a = a;
    }
}